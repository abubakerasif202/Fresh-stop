/**
 * Read-only catalogue image audit. Never touches a database. Writes one markdown report.
 * Usage: npx tsx scripts/catalogue-image-audit.ts
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { catalogueCandidates, PLACEHOLDER_IMAGE_URL } from "../src/data/catalogue-candidates";
import { CATALOGUE_ADDITIONS } from "../prisma/catalogue-additions";

const root = process.cwd();
const REPORT = path.join(root, "artifacts/catalogue-qa/image-audit.md");
const MANIFEST = path.join(root, "artifacts/image-generation/new-image-manifest.json");

interface Row { source: string; slug: string; name: string; category: string; image: string; exists: boolean; match: string }

const STOP = new Set(["fresh", "plain", "frozen", "mixed", "punjabi", "and", "of"]);
const tokens = (s: string) => s.toLowerCase().replace(/\([^)]*\)/g, " ").split(/[^a-z0-9]+/).filter(Boolean).map(w => w.replace(/(ies)$/, "y").replace(/s$/, "")).filter(w => !STOP.has(w));

export function judgeMatch(name: string, image: string): string {
  if (image === PLACEHOLDER_IMAGE_URL) return "placeholder";
  const base = path.basename(image, path.extname(image));
  const a = new Set(tokens(name)); const b = new Set(tokens(base));
  const shared = [...a].filter(t => b.has(t)).length;
  if (shared === 0) return "REVIEW: no filename overlap";
  if (shared === a.size && shared === b.size) return "ok (filename)";
  if (shared === a.size || shared === b.size) return "ok (partial filename)";
  return "REVIEW: partial overlap";
}

const rows: Row[] = [];
const add = (source: string, slug: string, name: string, category: string, image: string) =>
  rows.push({ source, slug, name, category, image, exists: existsSync(path.join(root, "public", image)), match: judgeMatch(name, image) });

const baseline = JSON.parse(readFileSync(path.join(root, "src/data/catalogue-baseline.json"), "utf8")) as { products: { slug: string; name: string; imageUrl: string; category: { slug: string } }[] };
for (const p of baseline.products) add("baseline", p.slug, p.name, p.category.slug, p.imageUrl);
for (const c of catalogueCandidates) add("candidate", c.slug, c.name, c.categorySlug, c.imageUrl);
for (const a of CATALOGUE_ADDITIONS) add("prisma-additions", a.slug, a.name, a.categorySlug, `/products/ai/${a.slug}.webp`);

// Keep the shared fallback even when every current candidate has an approved image.
const referenced = new Set([PLACEHOLDER_IMAGE_URL, ...rows.map(r => r.image)]);
const orphans: string[] = [];
for (const dir of ["products", "products/ai"]) {
  const abs = path.join(root, "public", dir);
  if (!existsSync(abs)) continue;
  for (const f of readdirSync(abs)) {
    if (!/\.(webp|png|jpe?g)$/i.test(f)) continue;
    const url = `/${dir}/${f}`;
    if (!referenced.has(url)) orphans.push(url);
  }
}
const missing = rows.filter(r => !r.exists && r.image !== PLACEHOLDER_IMAGE_URL);
const review = rows.filter(r => r.match.startsWith("REVIEW"));
const placeholders = rows.filter(r => r.image === PLACEHOLDER_IMAGE_URL);

let pending: { slug: string; targetPath: string; status: string }[] = [];
try { pending = JSON.parse(readFileSync(MANIFEST, "utf8")); } catch { /* manifest optional */ }
const ready = pending.filter(m => m.status === "pending" && existsSync(path.join(root, m.targetPath)));

/** Manual visual spot-checks (images opened and viewed). Update when more are reviewed. */
const SPOT_CHECKS = [
  "fresh-green-chillies.webp: long green chillies, clean cream background, matches 'Chillies' (green only; does not represent red chillies or jalapenos).",
  "fresh-lettuce.webp: two crinkled green lettuce heads, matches 'Lettuce' (generic leaf type; not iceberg/cos/butter).",
  "fresh-white-radish-daikon.webp: three daikon with leafy tops, matches name.",
  "fresh-honeydew-melon.webp: pale melon plus wedge, matches name. All four are square, light neutral background, no text; good quality.",
  "The 3 'REVIEW' baseline rows are false positives from extra descriptive words in the name (Australian / Local Free Range / Crisp Green); filenames are correct."
];

const cell = (s: string) => s.replace(/\|/g, "\|");
const table = (rs: Row[]) => ["| Source | Slug | Name | Category | Image | Exists | Match |", "|---|---|---|---|---|---|---|",
  ...rs.map(r => `| ${r.source} | ${cell(r.slug)} | ${cell(r.name)} | ${r.category} | ${r.image} | ${r.exists ? "yes" : "NO"} | ${r.match} |`)].join("\n");

const md = [
  "# Catalogue image audit", "",
  "Generated by `scripts/catalogue-image-audit.ts` (read-only; no database access). Match is judged from filenames only; visual spot-checks are listed separately.", "",
  `- Rows audited: ${rows.length} (baseline ${baseline.products.length}, candidates ${catalogueCandidates.length}, prisma additions ${CATALOGUE_ADDITIONS.length})`,
  `- Missing image files (non-placeholder): ${missing.length}`,
  `- Placeholder-image rows: ${placeholders.length}`,
  `- Filename match needing review: ${review.length}`,
  `- Orphan image files (not referenced by any row): ${orphans.length}`,
  `- Manifest images pending: ${pending.filter(m => m.status === "pending").length}; files already present and ready to flip: ${ready.length}${ready.length ? ` (${ready.map(m => m.slug).join(", ")})` : ""}`, "",
  "## Visual spot-checks", "", ...SPOT_CHECKS.map(n => `- ${n}`), "",
  "## Missing references", "", missing.length ? table(missing) : "None.", "",
  "## Needs review (filename)", "", review.length ? table(review) : "None.", "",
  "## Orphan images", "", orphans.length ? orphans.map(o => `- ${o}`).join("\n") : "None.", "",
  "## Full table", "", table(rows), ""
].join("\n");

mkdirSync(path.dirname(REPORT), { recursive: true });
writeFileSync(REPORT, md);
console.log(`Wrote ${path.relative(root, REPORT)}: ${rows.length} rows, ${missing.length} missing, ${review.length} review, ${orphans.length} orphans, ${ready.length} ready to flip`);
