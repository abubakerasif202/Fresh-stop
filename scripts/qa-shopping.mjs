import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(path.join(process.env.QA_TOOL_ROOT, "package.json"));
const { chromium } = require("playwright");
const base = process.env.BASE_URL || "http://localhost:3100";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(base).hostname));
assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(new URL(process.env.DATABASE_URL || "postgresql://invalid/invalid").hostname), "Shopping writes require a disposable localhost database");
assert.equal(process.env.ALLOW_LOCAL_E2E_WRITES, "1");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const checks = [];
const errors = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(`${base}/products`, { waitUntil: "networkidle" });
  const search = page.getByRole("searchbox", { name: "Search fresh produce", exact: true });
  await search.fill("banana");
  await search.locator("..").getByRole("link", { name: "Cavendish Bananas", exact: true }).waitFor();
  await search.press("Escape");
  await search.locator("..").getByRole("link", { name: "Cavendish Bananas", exact: true }).waitFor({ state: "hidden" });
  checks.push("Debounced search suggestions and Escape dismissal");
  await page.getByRole("navigation", { name: "Catalogue filters" }).getByRole("link", { name: "Fresh Fruits", exact: true }).click();
  await page.waitForURL(/category=fruits/);
  assert.match(await page.locator("h1").innerText(), /Fruit/i);
  checks.push("Category navigation");
  await page.getByLabel("Sort by", { exact: true }).selectOption("name");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await page.waitForURL(/sort=name/);
  const names = await page.locator("article h2").allTextContents();
  assert.ok(names.length > 0, "Sorting must inspect real catalogue products");
  assert.deepEqual(names, [...names].sort((a, b) => a.localeCompare(b)));
  checks.push("Catalogue name sorting");
  const catalogue = await page.request.get(`${base}/api/products?category=fruits&sort=price-asc`);
  assert.equal(catalogue.status(), 200);
  const products = await catalogue.json();
  const product = products[0];
  await page.goto(`${base}/products/${product.slug}`, { waitUntil: "networkidle" });
  assert.equal(await page.locator("h1").innerText(), product.name);
  await page.getByRole("button", { name: `Save ${product.name} to wishlist`, exact: true }).click();
  await page.reload({ waitUntil: "networkidle" });
  assert.ok(await page.getByRole("button", { name: `Remove ${product.name} from wishlist`, exact: true }).first().getAttribute("aria-pressed") === "true");
  checks.push("Product details and persistent wishlist");
  await page.getByRole("button", { name: "Add to basket", exact: true }).click();
  await page.getByRole("button", { name: "Close cart drawer" }).click();
  await page.goto(`${base}/checkout`, { waitUntil: "networkidle" });
  await page.locator("#fullname").fill("Browser QA Shopper");
  await page.locator("#email").fill("browser@example.test");
  await page.locator("#phone").fill("0412345678");
  await page.locator("#timeslot").selectOption({ index: 1 });
  let firstKey;
  let firstOrder;
  await page.route("**/api/checkout", async route => {
    firstKey = route.request().headers()["idempotency-key"];
    const response = await route.fetch();
    firstOrder = await response.json();
    assert.equal(response.status(), 200);
    await route.abort("failed");
  }, { times: 1 });
  await page.locator('#checkout-form button[type="submit"]').click();
  await page.getByRole("alert").waitFor();
  await page.reload({ waitUntil: "networkidle" });
  await page.locator("#fullname").fill("Browser QA Shopper");
  await page.locator("#email").fill("browser@example.test");
  await page.locator("#phone").fill("0412345678");
  await page.locator("#timeslot").selectOption({ index: 1 });
  const retry = page.waitForRequest(request => request.url().endsWith("/api/checkout"));
  await page.locator('#checkout-form button[type="submit"]').click();
  assert.equal((await retry).headers()["idempotency-key"], firstKey);
  await page.waitForURL(/order-confirmation\/.*\?t=/);
  assert.ok(page.url().includes(firstOrder.orderId));
  checks.push("Lost checkout response and browser reload reuse the completed order");
  assert.match(await page.locator("h1").innerText(), /Browser QA Shopper/);
  await page.screenshot({ path: "artifacts/qa/confirmation-desktop.png", fullPage: true, animations: "disabled" });
  checks.push("Browser guest pickup checkout and private confirmation");
  await page.goto(`${base}/orders`, { waitUntil: "networkidle" });
  await page.getByLabel("Order reference", { exact: true }).fill(firstOrder.orderNumber);
  await page.getByLabel("Email address", { exact: true }).fill("browser@example.test");
  await page.getByRole("button", { name: "View order", exact: true }).click();
  await page.waitForURL(/order-confirmation\/.*\?t=/);
  assert.ok(page.url().includes(firstOrder.orderId));
  checks.push("Order lookup form restores private confirmation using reference and email");
  await page.goto(`${base}/not-a-real-page`);
  assert.match(await page.locator("h1").innerText(), /isn’t here/);
  checks.push("Branded 404");
  assert.equal(errors.length, 0);
} finally {
  await writeFile("artifacts/qa/shopping-report.json", JSON.stringify({ checks, errors }, null, 2));
  await browser.close();
}
console.log(checks.join("\n"));
